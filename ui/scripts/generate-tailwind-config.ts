// F004 T006 — Tailwind config codegen.
//
// Reads ui/design-tokens.json (a static JSON export of
// the encrypted .pen file's design tokens, committed to git separately
// from the .pen source) and emits ui/tailwind.config.ts.
//
// CI runs:
//   cd ui && pnpm gen:tailwind && git diff --exit-code tailwind.config.ts
// to detect drift. Drift fails CI.
//
// USAGE:
//   pnpm gen:tailwind
// (invoked via the `gen:tailwind` npm script in package.json.)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const TOKENS_PATH = path.resolve(__dirname, "../design-tokens.json");
const OUTPUT_PATH = path.resolve(__dirname, "../tailwind.config.ts");

interface DesignTokens {
  colors: Record<string, string>;
  fontFamilies?: Record<string, string[]>;
  spacing?: Record<string, string>;
  radii?: Record<string, string>;
  shadows?: Record<string, string>;
}

function loadTokens(): DesignTokens {
  if (!existsSync(TOKENS_PATH)) {
    console.warn(
      `[gen:tailwind] No tokens file at ${TOKENS_PATH}; emitting placeholder config.`,
    );
    // Bootstrap baseline matching tailwind.config.ts placeholder. Allows
    // CI to pass before the first pen-file token export lands.
    return {
      colors: {
        "r5e-bg": "#0a0a0f",
        "r5e-surface": "#13131a",
        "r5e-border": "#26262e",
        "r5e-text": "#e8e8ee",
        "r5e-muted": "#8a8a92",
        "r5e-accent": "#7c5cff",
        "r5e-accent-glow": "#a385ff",
        "r5e-success": "#3ddc97",
        "r5e-danger": "#ff5e7e",
        "r5e-warning": "#ffb84d",
      },
      fontFamilies: {
        sans: ["Inter", "system-ui", "sans-serif"],
        mono: ["JetBrains Mono", "ui-monospace", "monospace"],
      },
    };
  }
  return JSON.parse(readFileSync(TOKENS_PATH, "utf8")) as DesignTokens;
}

function emit(tokens: DesignTokens): string {
  // Sort keys for deterministic output — same input MUST produce identical
  // bytes so the CI staleness gate is meaningful.
  const sortedColors = Object.fromEntries(
    Object.entries(tokens.colors).sort(([a], [b]) => a.localeCompare(b)),
  );
  const fontFamilies = tokens.fontFamilies ?? {
    sans: ["Inter", "system-ui", "sans-serif"],
    mono: ["JetBrains Mono", "ui-monospace", "monospace"],
  };

  const themeExtend: Record<string, unknown> = {
    colors: sortedColors,
    fontFamily: fontFamilies,
  };
  if (tokens.spacing) themeExtend.spacing = tokens.spacing;
  if (tokens.radii) themeExtend.borderRadius = tokens.radii;
  if (tokens.shadows) themeExtend.boxShadow = tokens.shadows;

  return `// F004 T006 — Tailwind config (GENERATED by scripts/generate-tailwind-config.ts).
// DO NOT HAND-EDIT. Regenerate with \`pnpm gen:tailwind\`.
// CI staleness gate: \`git diff --exit-code tailwind.config.ts\` after gen.

import type { Config } from "tailwindcss";

const config: Config = {
  content: [
    "./index.html",
    "./src/**/*.{ts,tsx}",
  ],
  theme: {
    extend: ${JSON.stringify(themeExtend, null, 6).replace(/\n/g, "\n    ")},
  },
  plugins: [],
};

export default config;
`;
}

function main(): void {
  const tokens = loadTokens();
  const out = emit(tokens);
  writeFileSync(OUTPUT_PATH, out, "utf8");
  console.log(`[gen:tailwind] wrote ${OUTPUT_PATH}`);
}

main();
