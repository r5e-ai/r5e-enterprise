// F004 T007 — JSON Schema → TypeScript codegen.
//
// Reads apps/recurse_gateway/priv/schemas/*.json from disk (file-based
// per research D10 — no running Gateway required), runs each through
// json-schema-to-typescript, concatenates the union of types, and writes
// ui/src/lib/types.ts.
//
// `types.ts` IS COMMITTED. CI runs:
//   cd ui && pnpm gen:types && git diff --exit-code src/lib/types.ts
// Drift between the schemas and the committed types FAILS CI.
//
// USAGE:
//   pnpm gen:types
// (invoked via the `gen:types` npm script in package.json.)

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SCHEMAS_DIR = path.resolve(__dirname, "../../apps/recurse_gateway/priv/schemas");
const OUTPUT_PATH = path.resolve(__dirname, "../src/lib/types.ts");

function listSchemaFiles(): string[] {
  const entries = readdirSync(SCHEMAS_DIR);
  return entries
    .filter((f) => f.endsWith(".json"))
    .sort() // deterministic order — same input MUST produce identical bytes
    .map((f) => path.join(SCHEMAS_DIR, f));
}

function checksum(files: string[]): string {
  const hash = createHash("sha256");
  for (const f of files) {
    hash.update(path.basename(f));
    hash.update("\0");
    hash.update(readFileSync(f));
    hash.update("\0");
  }
  return hash.digest("hex");
}

async function main(): Promise<void> {
  const files = listSchemaFiles();
  if (files.length === 0) {
    throw new Error(
      `[gen:types] No schemas found in ${SCHEMAS_DIR}. T008 should have populated this dir with skeletal schemas.`,
    );
  }

  const blocks: string[] = [];
  for (const file of files) {
    const ts = await compileFromFile(file, {
      bannerComment: "", // single shared banner at top
      style: { singleQuote: false, trailingComma: "all" },
      additionalProperties: false,
      strictIndexSignatures: true,
    });
    blocks.push(ts.trim());
  }

  const sum = checksum(files);
  const banner = `// F004 — Audit Console SPA TypeScript types (GENERATED by scripts/generate-types.ts).
// DO NOT HAND-EDIT. Regenerate with \`pnpm gen:types\` (CI staleness gate enforced).
//
// Source schemas (sorted):
${files.map((f) => `//   - ${path.relative(path.resolve(__dirname, "../.."), f)}`).join("\n")}
//
// Schema-set checksum (sha256): ${sum}
`;

  const out = `${banner}
export const SCHEMAS_CHECKSUM = "${sum}" as const;

${blocks.join("\n\n")}
`;

  mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, out, "utf8");
  console.log(`[gen:types] wrote ${OUTPUT_PATH} (${files.length} schemas, checksum ${sum.slice(0, 12)}…)`);
}

main().catch((err) => {
  console.error("[gen:types] FAILED:", err);
  process.exit(1);
});
