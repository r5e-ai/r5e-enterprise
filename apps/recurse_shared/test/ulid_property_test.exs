defmodule Recurse.Shared.UlidPropertyTest do
  use ExUnit.Case, async: true
  use ExUnitProperties

  alias Recurse.Shared.Ulid

  @crockford_regex ~r/^[0-9A-HJKMNP-TV-Z]{26}$/

  describe "generate/0" do
    property "is 26 characters of Crockford-Base32" do
      check all(_ <- StreamData.constant(nil), max_runs: 200) do
        ulid = Ulid.generate()
        assert byte_size(ulid) == 26
        assert ulid =~ @crockford_regex
      end
    end

    property "is reversibly parseable: parse!/1 |> to_string/1 round-trips" do
      check all(_ <- StreamData.constant(nil), max_runs: 200) do
        ulid = Ulid.generate()
        parsed = Ulid.parse!(ulid)
        assert Ulid.to_string(parsed) == ulid
      end
    end

    property "generate returns monotonically increasing values in a tight burst" do
      check all(count <- StreamData.integer(2..64), max_runs: 50) do
        ulids = for _ <- 1..count, do: Ulid.generate()
        sorted = Enum.sort(ulids)
        assert ulids == sorted, "ULIDs were not monotonically increasing: #{inspect(ulids)}"
        # No duplicates either.
        assert length(Enum.uniq(ulids)) == count
      end
    end

    # Regression test for speckit-pr-review F002 (TOCTOU race in
    # monotonic_randomness/1). Spawns N concurrent processes all calling
    # generate/0 in parallel; invariant is that every ULID is unique.
    property "generate is unique under concurrent callers" do
      check all(count <- StreamData.integer(16..128), max_runs: 25) do
        ulids =
          1..count
          |> Task.async_stream(fn _ -> Ulid.generate() end,
            max_concurrency: count,
            ordered: false,
            timeout: :timer.seconds(5)
          )
          |> Enum.map(fn {:ok, u} -> u end)

        assert length(Enum.uniq(ulids)) == count,
               "concurrent ULIDs collided — had #{length(ulids) - length(Enum.uniq(ulids))} duplicates"
      end
    end
  end

  describe "parse/1" do
    property "rejects strings of the wrong length" do
      check all(bin <- StreamData.binary(min_length: 0, max_length: 25)) do
        assert {:error, _} = Ulid.parse(bin)
      end
    end

    property "accepts canonical-form ULIDs generated by generate/0" do
      check all(_ <- StreamData.constant(nil), max_runs: 100) do
        ulid = Ulid.generate()
        assert {:ok, %Ulid{string: ^ulid}} = Ulid.parse(ulid)
      end
    end
  end
end
