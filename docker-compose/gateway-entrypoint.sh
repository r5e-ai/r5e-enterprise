#!/usr/bin/env bash
# Gateway container entrypoint (spec 012 S1).
#
# Runs before `bin/audit_console start`:
#
#   0. Refuse to boot on a placeholder / short SECRET_KEY_BASE. The release
#      raises on it anyway (config/runtime.exs), but under
#      `restart: unless-stopped` that reads as an endless "Restarting";
#      one plain line naming `bin/r5e init` is kinder.
#   1. Materialise first-boot secrets into the `secrets` volume:
#        * the broker ES256 PEM that BROKER_JWT_SIGNING_KEY_PATH points at
#          (the collapsed broker + dev login mint browser-session JWTs
#          with it; same shape scripts/gen-broker-key.sh produces).
#        The attestation signing key (R5E_LOCAL_SIGNING_KEY_PATH) is
#        generated by LocalPemSecretsProvider.init/1 itself, so it is NOT
#        touched here — the provider owns its key's algorithm.
#   2. Create the CAS root so the FilesystemStorageProvider healthcheck is
#      green from the first request.
#   2b. Policy volume seeding (spec 012 S5). compose mounts a named
#      volume at /policy (what RECURSE_POLICY_BUNDLE_PATH points into)
#      and bind-mounts the checkout's ./policy read-only at
#      /policy-default. With R5E_POLICY_GIT_URL unset, /policy/bundle.cedar
#      is made a symlink to /policy-default/bundle.cedar, so the file in
#      the checkout stays live (edit it, the poller reloads it). With it
#      set, the symlink is left for `policy-sync` to replace with a real
#      file (rename over a symlink swaps the link itself), or, if the
#      volume has no bundle yet, a COPY of the default is seeded so the
#      gateway can boot before the first sync lands. A real file written
#      by policy-sync is never overwritten here while the URL is set.
#   3. Run Ecto migrations against the compose Postgres via
#      `bin/audit_console eval "Recurse.Gateway.Release.migrate()"`.
#      Retries ONLY while the database is unreachable (connection
#      refused / DNS / timeout patterns in the eval output):
#      `depends_on: service_healthy` covers the common case, but
#      pg_isready can pass a beat before Postgres accepts a real
#      connection. A migration that genuinely fails is printed once and
#      the container exits non-zero immediately; retrying it would only
#      turn a real error into a silent restart loop.
#   4. exec the release with whatever arguments compose passed
#      (default `start`), so signals reach the BEAM directly.
#
# Every path is env-driven; nothing here is specific to compose beyond
# the defaults, so the same image runs under any orchestrator that
# mounts /secrets and /data/cas.
set -euo pipefail

RELEASE_BIN="${RELEASE_BIN:-/app/bin/audit_console}"
BROKER_KEY="${BROKER_JWT_SIGNING_KEY_PATH:-/secrets/broker-signing-key.pem}"
CAS_ROOT="${R5E_CAS_ROOT:-/data/cas}"
SIGNING_KEY="${R5E_LOCAL_SIGNING_KEY_PATH:-/secrets/local-signing-key.pem}"
MIGRATE_ATTEMPTS="${R5E_MIGRATE_ATTEMPTS:-10}"
# Output that means "Postgres is not accepting connections yet" (Postgrex /
# DBConnection wording + the libpq-side 57P03 startup message). Anything
# else in a failed migrate is treated as a real error.
DB_UNREACHABLE_PATTERN='connection refused|econnrefused|nxdomain|DBConnection\.ConnectionError|tcp connect|could not connect|no route to host|ehostunreach|timed out|database system is starting up'

log() { echo "[entrypoint] $*"; }

# --- 0. config preflight ----------------------------------------------------
skb="${SECRET_KEY_BASE:-}"
if [ "${#skb}" -lt 32 ] || [ "${skb#REPLACE_ME}" != "$skb" ]; then
  log "SECRET_KEY_BASE is unset, still the .env.example placeholder, or shorter than 32 chars: run ./bin/r5e init (or put \`openssl rand -hex 32\` output in .env) and start again" >&2
  exit 78 # EX_CONFIG
fi

# --- 1. broker JWT signing key (ES256 / P-256, PKCS#8 PEM) -----------------
mkdir -p "$(dirname "$BROKER_KEY")" "$(dirname "$SIGNING_KEY")"
if [ ! -s "$BROKER_KEY" ]; then
  log "generating broker JWT signing key at $BROKER_KEY (ES256 P-256)"
  umask 077
  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out "$BROKER_KEY.tmp"
  mv "$BROKER_KEY.tmp" "$BROKER_KEY"
  umask 022
fi
chmod 600 "$BROKER_KEY" 2>/dev/null || true

# --- 2. CAS root ------------------------------------------------------------
mkdir -p "$CAS_ROOT"

# --- 2b. policy volume ------------------------------------------------------
POLICY_BUNDLE="${RECURSE_POLICY_BUNDLE_PATH:-/policy/bundle.cedar}"
POLICY_DEFAULT="${R5E_POLICY_DEFAULT_BUNDLE:-/policy-default/bundle.cedar}"
if [ -f "$POLICY_DEFAULT" ] && [ -d "$(dirname "$POLICY_BUNDLE")" ]; then
  if [ -z "${R5E_POLICY_GIT_URL:-}" ]; then
    if [ ! -L "$POLICY_BUNDLE" ] || [ "$(readlink "$POLICY_BUNDLE")" != "$POLICY_DEFAULT" ]; then
      log "policy: R5E_POLICY_GIT_URL unset; linking $POLICY_BUNDLE -> $POLICY_DEFAULT (the checkout's ./policy)"
      rm -f "$POLICY_BUNDLE"
      ln -s "$POLICY_DEFAULT" "$POLICY_BUNDLE"
    fi
  elif [ ! -e "$POLICY_BUNDLE" ]; then
    log "policy: no bundle in the volume yet; seeding a copy of $POLICY_DEFAULT until policy-sync delivers one"
    cp "$POLICY_DEFAULT" "$POLICY_BUNDLE.tmp.$$" && mv -f "$POLICY_BUNDLE.tmp.$$" "$POLICY_BUNDLE"
  elif [ -L "$POLICY_BUNDLE" ]; then
    log "policy: R5E_POLICY_GIT_URL set; $POLICY_BUNDLE still points at the checkout default until policy-sync delivers a bundle"
  else
    log "policy: using the policy-sync bundle in the volume ($POLICY_BUNDLE)"
  fi
fi

# --- 3. migrations ----------------------------------------------------------
if [ "${R5E_SKIP_MIGRATE:-false}" != "true" ]; then
  attempt=1
  while :; do
    if output="$("$RELEASE_BIN" eval 'Recurse.Gateway.Release.migrate()' 2>&1)"; then
      log "migrations up to date"
      break
    fi
    if printf '%s' "$output" | grep -Eiq "$DB_UNREACHABLE_PATTERN"; then
      if [ "$attempt" -ge "$MIGRATE_ATTEMPTS" ]; then
        log "database still unreachable after $attempt attempts; giving up" >&2
        printf '%s\n' "$output" >&2
        exit 1
      fi
      log "database not accepting connections yet (attempt $attempt/$MIGRATE_ATTEMPTS); retrying in 3s"
      attempt=$((attempt + 1))
      sleep 3
    else
      log "migration failed; not retrying (fix the migration or the database, then restart the gateway)" >&2
      printf '%s\n' "$output" >&2
      exit 1
    fi
  done
fi

# --- 4. run -----------------------------------------------------------------
if [ "$#" -eq 0 ]; then
  set -- start
fi
exec "$RELEASE_BIN" "$@"
